"""Failed / unclear prompts for a human to review (docs/INTENT_FAILURE_REVIEW.md, part G).

Reads the local `ambiguous_requests` table (what users typed that was not clear, and which chip they tapped) and the
latest intent eval failures, and writes docs/FAILED_PROMPTS_FOR_REVIEW.md:
  1. the most common unclear phrases (by meaning key), with what users picked
  2. proposed synonyms: phrases whose users picked the same skill at least twice (never added automatically — a
     person approves them; Hindi / Hinglish ones need a native speaker)
  3. the eval's failures (corpus label vs what the resolver chose)

    backend/.venv/Scripts/python.exe eval/review_failed_prompts.py [path/to/cutmind.sqlite3]
"""

from __future__ import annotations

import json
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    db_path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "data" / "cutmind.sqlite3"
    rows: list[dict] = []
    if db_path.exists():
        con = sqlite3.connect(db_path)
        con.row_factory = sqlite3.Row
        try:
            rows = [dict(r) for r in con.execute("SELECT * FROM ambiguous_requests ORDER BY created_at DESC")]
        except sqlite3.OperationalError:
            rows = []  # no unclear request logged yet
    by_key: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_key[r["key"] or r["prompt"]].append(r)
    lines = ["# Failed / unclear prompts — for a human to review", "",
             f"Generated by `eval/review_failed_prompts.py` from {db_path.name} ({len(rows)} unclear requests) and "
             "eval/results/intent_eval.json. Nothing here is added to the skills automatically.", "",
             "## 1. Most common unclear phrases", "", "| times | example as typed | choices shown | picked |",
             "|---|---|---|---|"]
    for k, rs in sorted(by_key.items(), key=lambda kv: -len(kv[1]))[:50]:
        picked = Counter(r["picked"] for r in rs if r["picked"])
        shown = json.loads(rs[0]["choices"] or "[]")
        lines.append(f"| {len(rs)} | {rs[0]['prompt'][:70]} | {', '.join(shown)} | "
                     f"{', '.join(f'{s} ×{n}' for s, n in picked.most_common()) or '—'} |")
    lines += ["", "## 2. Proposed synonyms (picked the same skill ≥ 2 times — approve or reject)", "",
              "| phrase (as typed) | skill | picks |", "|---|---|---|"]
    for _k, rs in by_key.items():
        picked = Counter(r["picked"] for r in rs if r["picked"])
        if picked and picked.most_common(1)[0][1] >= 2:
            sid, n = picked.most_common(1)[0]
            lines.append(f"| {rs[0]['prompt'][:70]} | `{sid}` | {n} |")
    ev = ROOT / "eval" / "results" / "intent_eval.json"
    if ev.exists():
        fails = json.loads(ev.read_text(encoding="utf-8"))["after"]["fails"]
        lines += ["", f"## 3. Eval failures ({len(fails)}; the corpus label may itself be debatable)", "",
                  "| prompt | corpus says | resolver chose (top 3) | applied without asking |", "|---|---|---|---|"]
        lines += [f"| {f['prompt']} | `{f['expect']}` | {', '.join(f['got'])} | {'yes' if f['applied'] else 'no'} |"
                  for f in fails]
    out = ROOT / "docs" / "FAILED_PROMPTS_FOR_REVIEW.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} unclear requests, {len(by_key)} distinct → {out}")


if __name__ == "__main__":
    main()
