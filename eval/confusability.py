"""Confusability lint: which skills steal each other's words (docs/UNDERSTANDING_REVIEW.md, Phase 3).

Every synonym of every skill, plus 2 machine misspellings of it (tools/variants.py), is scored by the token scorer.
When another skill ranks first, that pair counts one confusion. Writes docs/CONFUSABILITY.md (pairs, worst first,
with the phrases) and eval/results/confusability.json; exits 1 when a pair is confused more often than LIMIT
(a new skill that swallows another skill's words must get a disambiguation note or a merge).

    backend/.venv/Scripts/python.exe eval/confusability.py [--limit 6]
"""

from __future__ import annotations

import json
import random
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from cutmind.tools import spec  # noqa: E402
from cutmind.tools.fuzzy import canonical_words  # noqa: E402
from cutmind.tools.resolve import score_skills, warm  # noqa: E402
from cutmind.tools.variants import variants  # noqa: E402

LIMIT = 6  # confusions per pair before the lint fails
# pairs that are confused ON PURPOSE (a documented decision): reported, not failed
KNOWN = {("fade_white", "flash"), ("flash", "fade_white"), ("aspect_9_16", "export_preset"),
         ("export_preset", "aspect_9_16"), ("teal_orange", "cinematic_look"), ("cinematic_look", "teal_orange")}


def noisy(phrase: str, rnd: random.Random) -> str:
    words = phrase.split()
    cand = [i for i, w in enumerate(words) if variants(w)]
    if cand:
        i = rnd.choice(cand)
        words[i] = rnd.choice(variants(words[i]))
    return " ".join(words)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    limit = int(sys.argv[sys.argv.index("--limit") + 1]) if "--limit" in sys.argv else LIMIT
    warm()
    rnd = random.Random(11)
    pairs: dict[tuple[str, str], list[str]] = defaultdict(list)
    tested = defaultdict(int)
    for sid, s in sorted(spec.load().items()):
        for p in (p for ps in s["synonyms"].values() for p in ps):
            for q in (p, noisy(p, rnd), noisy(p, rnd)):
                sc = score_skills(canonical_words(q))
                if not sc:
                    continue
                tested[sid] += 1
                top = max(sc, key=lambda k: sc[k][0])
                if top != sid and sc[top][0] > sc.get(sid, (0.0, ""))[0] + 1e-6:
                    pairs[(sid, top)].append(q)
    rows = sorted(({"skill": a, "taken_by": b, "count": len(v), "of": tested[a], "examples": v[:4],
                    "known": (a, b) in KNOWN} for (a, b), v in pairs.items()), key=lambda r: -r["count"])
    bad = [r for r in rows if r["count"] > limit and not r["known"]]
    (ROOT / "eval" / "results" / "confusability.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False),
                                                                  encoding="utf-8")
    lines = ["# Confusability lint", "",
             "Generated by `eval/confusability.py`. Each skill's synonyms plus 2 machine misspellings each were scored; "
             "a row counts the phrases of a skill that another skill ranked higher.", "",
             f"Pairs over the limit ({limit}) and not a documented decision: **{len(bad)}**.", "",
             "| skill | taken by | times | of | examples | note |", "|---|---|---|---|---|---|"]
    lines += [f"| `{r['skill']}` | `{r['taken_by']}` | {r['count']} | {r['of']} | {'; '.join(r['examples'][:3])} | "
              f"{'documented decision' if r['known'] else ('OVER LIMIT' if r['count'] > limit else '')} |" for r in rows[:60]]
    (ROOT / "docs" / "CONFUSABILITY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} confused pairs, {len(bad)} over the limit")
    for r in rows[:12]:
        print(f"  {r['skill']:22} ← {r['taken_by']:22} {r['count']}/{r['of']}  e.g. {r['examples'][0]}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
