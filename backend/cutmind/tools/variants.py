"""Synthetic spelling variants of the words in the skills' synonyms (own code).

How people mistype Hinglish (cf. the noisy-form rules in arXiv 1804.05868, written here from the idea, no code
taken): non-initial vowels dropped ("karo" → "kro"), phonetically close consonants swapped (v/w, z/j, ph/f, s/sh,
c/k), a vowel stretched ("haan" ← "han"), a consonant doubled ("zoom" → "zzoom" is rare; "glitch" → "glittch"),
and common Hinglish endings ("-o" / "-u").

`variant_map()` maps every generated variant to the real synonym word it came from — only when that variant is
not itself a real word of another skill (a variant that collides is dropped, never guessed). The table is written
to catalog/generated_variants.json for review; fuzzy.canonical_words uses it after the hand-written VARIANTS.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

SWAPS = [("w", "v"), ("v", "w"), ("z", "j"), ("j", "z"), ("ph", "f"), ("f", "ph"), ("sh", "s"), ("s", "sh"),
         ("c", "k"), ("k", "c"), ("ee", "i"), ("i", "ee"), ("oo", "u"), ("u", "oo"), ("aa", "a"), ("a", "aa")]
VOWELS = "aeiou"


def variants(word: str, limit: int = 12) -> list[str]:
    """Plausible misspellings of one word (deterministic order, the word itself excluded)."""
    w = word.lower()
    if len(w) < 4 or not w.isalpha():
        return []
    out: list[str] = []

    def add(x: str) -> None:
        if x != w and len(x) >= 3 and x not in out:
            out.append(x)

    add(w[0] + re.sub(f"[{VOWELS}]", "", w[1:]))            # all non-initial vowels dropped: "karo" → "kr"
    add(w[0] + re.sub(f"[{VOWELS}](?=[^{VOWELS}])", "", w[1:]))  # inner vowels dropped, last kept: "karo" → "kro"
    for a, b in SWAPS:
        if a in w:
            add(w.replace(a, b, 1))
    for i in range(1, len(w)):                               # one letter dropped / doubled
        add(w[:i] + w[i + 1:])
        if w[i] not in VOWELS:
            add(w[:i] + w[i] + w[i:])
    if w.endswith("o"):
        add(w[:-1] + "u")
    return out[:limit]


@lru_cache(maxsize=1)
def variant_map() -> dict[str, str]:
    """generated variant → the synonym word it came from (collisions with real words or with two sources dropped)."""
    from . import spec
    from .fuzzy import FILLER

    real: set[str] = set()
    for s in spec.load().values():
        for phrases in s["synonyms"].values():
            for p in phrases:
                real.update(re.findall(r"[a-z]+", p.lower()))
    real |= set(FILLER)
    from ..prenormalize import COMMON_ENGLISH, HINGLISH

    # a "variant" that is a common word of its own ("safe" from "safed") is not a typo: never mapped
    real |= set(COMMON_ENGLISH) | set(HINGLISH) | {"safe", "same", "come", "some", "time", "line", "more", "make",
                                                     "take", "like", "here", "there", "fast", "last", "part", "start"}
    seen: dict[str, str] = {}
    clash: set[str] = set()
    for word in sorted(real):
        if word in FILLER:
            continue
        for v in variants(word):
            if v in real:
                continue
            if v in seen and seen[v] != word:
                clash.add(v)
            seen.setdefault(v, word)
    return {v: w for v, w in seen.items() if v not in clash}


def write_review_file(root: Path) -> Path:
    out = root / "catalog" / "generated_variants.json"
    m = variant_map()
    out.write_text(json.dumps({"note": "generated by backend/cutmind/tools/variants.py — review, never hand-edit",
                               "count": len(m), "variants": dict(sorted(m.items()))}, indent=0, ensure_ascii=False),
                   encoding="utf-8")
    return out
