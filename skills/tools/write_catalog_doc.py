"""Writes docs/SKILL_CATALOG.md from the registry + skills/test_results.json (never by hand).

    backend/.venv/Scripts/python.exe skills/tools/write_catalog_doc.py
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from cutmind import skill_registry as R  # noqa: E402

STATUS = {"tested": "tested", "untested": "NOT TESTED", "planned": "planned", "blocked": "BLOCKED"}


def _cell(x: str) -> str:
    return str(x).replace("|", "\\|").replace("\n", " ")


def main() -> None:
    reg = R.load()
    res_path = ROOT / "skills" / "test_results.json"
    results = json.loads(res_path.read_text(encoding="utf-8")) if res_path.exists() else {}
    count = Counter((s["tier"], s["status"]) for s in reg.values())
    lines = [
        "# Skill catalog",
        "",
        "Generated by `skills/tools/write_catalog_doc.py` from `skills/registry/*.yaml` and `skills/test_results.json`.",
        "Do not edit by hand. **tested** = a real FFmpeg render (or a full pipeline run) was measured by",
        "`tests/integration/test_skill_renders.py` / `test_skill_pipeline.py`; **NOT TESTED** = built, no measured test",
        "yet; **planned** / **BLOCKED** = cannot be used for an edit (the enhancer says so).",
        "",
        f"Total: {len(reg)} skills.",
        "",
        "| Tier | tested | NOT TESTED | planned | blocked |",
        "|---|---|---|---|---|",
    ]
    for t in (1, 2, 3):
        lines.append(f"| {t} | {count[(t, 'tested')]} | {count[(t, 'untested')]} | {count[(t, 'planned')]} | "
                     f"{count[(t, 'blocked')]} |")
    for t in (1, 2, 3):
        lines += ["", f"## Tier {t}", "", "| id | name | category | kind | status | measured | example |",
                  "|---|---|---|---|---|---|---|"]
        for sid, s in sorted(reg.items(), key=lambda kv: (kv[1]["category"], kv[0])):
            if s["tier"] != t:
                continue
            r = results.get(sid, {})
            measured = r.get("detail", "") if r else (s["impl"].get("reason", "") if s["status"] in ("planned", "blocked")
                                                      else "")
            lines.append(f"| `{sid}` | {_cell(s['name'])} | {s['category']} | {s['impl']['kind']} | "
                         f"{STATUS[s['status']]} | {_cell(measured)[:140]} | {_cell(s['examples'][0])} |")
    out = ROOT / "docs" / "SKILL_CATALOG.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out, len(reg))


if __name__ == "__main__":
    main()
