"""Writes docs/TIER1_STATUS.md and docs/SYNONYMS_FOR_HUMAN_REVIEW.md from the specs and the test results
(skills/tier1_results.json, eval/results/tier1_lang*.json). Never edit those docs by hand.

    backend/.venv/Scripts/python.exe skills/tools/write_tier1_docs.py
"""

from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from cutmind.tools import spec  # noqa: E402

DEV = re.compile(r"[ऀ-ॿ]")
CAT_ORDER = ["cutting", "layout", "color", "motion", "transitions", "audio", "text", "stylize", "delivery"]


def cell(x: object) -> str:
    return str(x).replace("|", "\\|").replace("\n", " ")


def main() -> None:
    specs = spec.load()
    res = json.loads((ROOT / "skills" / "tier1_results.json").read_text(encoding="utf-8"))
    lang_p = ROOT / "eval" / "results" / "tier1_lang.json"
    lang = json.loads(lang_p.read_text(encoding="utf-8")) if lang_p.exists() else {"per_skill": {}}
    held_p = ROOT / "eval" / "results" / "tier1_lang_heldout.json"
    held = json.loads(held_p.read_text(encoding="utf-8")) if held_p.exists() else None
    tested = sum(1 for s in specs if res.get(s, {}).get("ok"))
    m3 = Counter(s["media3"]["status"] for s in specs.values())
    lines = [
        "# Tier 1 status",
        "",
        "Generated by `skills/tools/write_tier1_docs.py` from `skills/tier1/*.yaml`, `skills/tier1_results.json` "
        "(render tests: `tests/integration/test_tier1.py`) and `eval/results/tier1_lang*.json`. Do not edit by hand.",
        "",
        f"- **{len(specs)} skills** (the founder's 100 + 5 added in TIER1_REVIEW: crop, stabilize, loop_boomerang, "
        "thumbnail, srt_export). Implemented: all; tested (a real FFmpeg render measured): "
        f"**{tested}/{len(specs)}**.",
        f"- Media3 (phone): mapped {m3['mapped']}, custom shader needed {m3['custom_shader']}, server-only "
        f"{m3['server_only']}. **Every Media3 mapping is NOT TESTED** (no Android device in this work).",
        f"- Language (the YAML examples, seen while writing the synonyms): {lang.get('correct', '?')}/"
        f"{lang.get('prompts', '?')} = {lang.get('accuracy', 0):.1%}; by language {lang.get('by_lang', {})}.",
    ]
    if held:
        lines.append(f"- Language, HELD-OUT (written after the synonyms were frozen): {held['correct']}/{held['prompts']} "
                     f"= {held['accuracy']:.1%}; multi-skill prompts {held['multi']['exact']}/{held['multi']['prompts']} "
                     f"exact (mean recall {held['multi']['mean_recall']}).")
    lines += ["", "| # | skill | category | implemented | render test | language (8) | Media3 | server-only | known limits |",
              "|---|---|---|---|---|---|---|---|---|"]
    for cat in CAT_ORDER:
        for sid, s in sorted(((k, v) for k, v in specs.items() if v["category"] == cat), key=lambda kv: kv[1]["seed"]):
            r = res.get(sid, {})
            test = ("✅ " + cell(r.get("detail", ""))[:110]) if r.get("ok") else ("❌ " + cell(r.get("detail", "not run"))[:110])
            m = s["media3"]
            lines.append(f"| {s['seed']} | `{sid}` | {cat} | yes | {test} | {lang.get('per_skill', {}).get(sid, '?')} | "
                         f"{m['status']}{' — ' + cell(m.get('how', ''))[:60] if m.get('how') else ''} | "
                         f"{'yes — ' + cell(m.get('reason', '')) if m['status'] == 'server_only' else 'no'} | "
                         f"{cell(s.get('limits', ''))[:140]} |")
    (ROOT / "docs" / "TIER1_STATUS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # ---- Hindi / Hinglish for a human --------------------------------------------------------------------------
    rev = [
        "# Hindi / Hinglish phrases for a native speaker to check",
        "",
        "Generated by `skills/tools/write_tier1_docs.py`. I (the coding agent) am not a native speaker. Please mark "
        "every phrase that sounds wrong, unnatural, or means something else, and add the words people really say. "
        "Edit the skill's YAML (`skills/tier1/<id>.yaml`) or send the list back.",
        "",
        "## 1. Decisions about ambiguous words (please confirm)",
        "",
        "| phrase | I made it mean | could also mean |",
        "|---|---|---|",
        "| kaato / kaat do (alone) | asks which: trim / split / delete need times | any cut |",
        "| chhota karo | the video's length (fit_to_duration) | text size (\"text chhota karo\" is text size) |",
        "| tez karo (alone) | speed (speed_up) | volume (\"awaaz tez\" is volume) |",
        "| saaf karo / awaaz saaf karo | sharpen (picture) / denoise (sound) | voice clarity EQ |",
        "| mirror (alone) | flip the picture (rotate_flip) | the symmetric mirror effect (\"mirror effect\") |",
        "| status | WhatsApp Status (9:16, ≤ 30 s) | progress / status bar |",
        "| highlight / highlights | best moments (extract_highlights) | a circle / arrow on screen (\"yahan highlight karo\") |",
        "| 90s wala look | VHS tape look | faded vintage colours |",
        "| aaine jaisa / ulta seedha | mirror effect | flip |",
        "",
        "## 2. Hindi filler sounds removed by remove_fillers",
        "",
        "Removed: aa, aaa, aah, umm, hmm, हम्म, आ, अ. **Not** removed (often real words): matlab, toh, na, haan, "
        "basically. Should any of these be removed, or any removed one be kept?",
        "",
        "## 3. Every Devanagari phrase (synonyms and example prompts)",
        "",
        "| skill | phrase | where |",
        "|---|---|---|",
    ]
    for sid, s in sorted(specs.items(), key=lambda kv: kv[1]["seed"]):
        for group, syns in s["synonyms"].items():
            for x in syns:
                if DEV.search(x):
                    rev.append(f"| `{sid}` | {cell(x)} | synonym ({group}) |")
        for e in s["examples"]:
            if DEV.search(e["prompt"]):
                rev.append(f"| `{sid}` | {cell(e['prompt'])} | example |")
    rev += ["", "## 4. Hinglish synonyms I am least sure about", "",
            "Spellings vary a lot (bahut / bohot / bht). The parser normalises many, but please flag phrases nobody says.", "",
            "| skill | phrase |", "|---|---|"]
    unsure = re.compile(r"\b(?:chust|dhamakedar|jhakaas|nipta|khinch|chipka|phatak|fatak|gunj|kampan|mahaul|thappa|uda)\w*")
    for sid, s in sorted(specs.items(), key=lambda kv: kv[1]["seed"]):
        for group in ("hinglish", "slang"):
            for x in s["synonyms"].get(group, []):
                if unsure.search(x):
                    rev.append(f"| `{sid}` | {cell(x)} |")
    (ROOT / "docs" / "SYNONYMS_FOR_HUMAN_REVIEW.md").write_text("\n".join(rev) + "\n", encoding="utf-8")
    print("TIER1_STATUS.md", tested, "/", len(specs), "| SYNONYMS_FOR_HUMAN_REVIEW.md", sum(1 for x in rev if x.startswith("| `")))


if __name__ == "__main__":
    main()
