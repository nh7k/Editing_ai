#!/usr/bin/env bash
# CutMind one-shot setup for macOS / Linux (and Git Bash on Windows). Safe to re-run.
set -euo pipefail
cd "$(dirname "$0")"

PY=python3; command -v $PY >/dev/null || PY=python
command -v $PY >/dev/null || { echo "[!] Python 3.11+ required"; exit 1; }
command -v node >/dev/null || { echo "[!] Node.js 20+ required (https://nodejs.org)"; exit 1; }
if ! command -v ffmpeg >/dev/null; then
  echo "[!] FFmpeg not found. Install it:"
  echo "    macOS:  brew install ffmpeg      Ubuntu/Debian: sudo apt install ffmpeg"
  echo "    Windows: winget install Gyan.FFmpeg.Essentials"
  exit 1
fi

echo "[*] Python virtualenv + backend packages"
[ -d backend/.venv ] || $PY -m venv backend/.venv
VPY=backend/.venv/bin/python; [ -x "$VPY" ] || VPY=backend/.venv/Scripts/python.exe
"$VPY" -m pip install --upgrade pip -q
"$VPY" -m pip install -r backend/requirements-dev.txt -q

echo "[*] Royalty-free music beds (generated by FFmpeg)"
(cd backend && "../$VPY" -m cutmind.media_gen --music assets/music)

echo "[*] Mobile app packages"
(cd mobile && npm install)

echo "[*] Downloading models: Qwen2.5-1.5B-Instruct ONNX (~1.8 GB) + faster-whisper tiny"
(cd backend && PLANNER_MODE=local "../$VPY" -m cutmind.prefetch)
echo "Done. Start everything with: ./run-all.sh"
